import { expect, test } from '@playwright/test'

test('crawlers get per-page open graph tags', async ({ request }) => {
  const home = await request.get('/', { headers: { 'User-Agent': 'facebookexternalhit/1.1' } })
  expect(home.status()).toBe(200)
  expect(home.headers()['content-type']).toContain('text/html')
  const homeHtml = await home.text()
  expect(homeHtml).toContain('<title>Bitcoin</title>')
  expect(homeHtml).toContain('name="description" content="Bitcoin กระดานถาม-ตอบ"')
  expect(homeHtml).toContain('property="og:description" content="Bitcoin กระดานถาม-ตอบ"')
  expect(homeHtml).not.toContain('คุยวง')
  expect(homeHtml).not.toContain('ห้องคุยสด')
  expect(homeHtml).toContain('property="og:site_name" content="Bitcoin"')
  expect(homeHtml).toContain('property="og:locale" content="th_TH"')
  expect(homeHtml).toContain('name="twitter:card" content="summary_large_image"')
  expect(homeHtml).toContain('/brand/share.png')
  expect(homeHtml).toContain('property="og:image:width" content="1200"')
  expect(homeHtml).toContain('property="og:image:height" content="630"')
  expect(homeHtml.match(/<title>/g)).toHaveLength(1)

  const topic = await request.get('/topic/1', { headers: { 'User-Agent': 'facebookexternalhit/1.1' } })
  expect(topic.status()).toBe(200)
  const topicHtml = await topic.text()
  expect(topicHtml).toContain('property="og:type" content="article"')
  expect(topicHtml).toContain('property="og:title" content="Welcome to Bitcoin"')
  expect(topicHtml).toContain('property="og:url" content="')
  expect(topicHtml).toContain('/topic/1"')
  expect(topicHtml).toContain('ยินดีต้อนรับสู่ Bitcoin')
  expect(topicHtml).not.toContain('[quote')
  expect(topicHtml).toContain('name="twitter:title" content="Welcome to Bitcoin"')
  expect(topicHtml).toContain('name="twitter:image"')

  const board = await request.get('/board/1', { headers: { 'User-Agent': 'facebookexternalhit/1.1' } })
  expect(board.status()).toBe(200)
  const boardHtml = await board.text()
  expect(boardHtml).toContain('property="og:title" content="Bitcoin Discussion"')
  expect(boardHtml).toContain('<title>Bitcoin Discussion · Bitcoin</title>')
})
