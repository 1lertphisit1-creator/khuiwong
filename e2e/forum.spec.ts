test('owner can moderate and guests stay read-only until allowed', async ({ browser }) => {
  const ownerContext = await browser.newContext()
  const guestContext = await browser.newContext()
  const owner = await ownerContext.newPage()
  const guest = await guestContext.newPage()

  await owner.goto('/')
  await owner.getByTestId('nav-login').click()
  await owner.getByLabel('ชื่อบัญชี').fill('fibo99')
  await owner.getByLabel('รหัสผ่าน').fill('owner-pass-99')
  await owner.getByRole('button', { name: 'เข้าสู่ระบบ' }).click()
  await expect(owner.getByTestId('forum-hello')).toContainText('Hello fibo99')
  await owner.getByTestId('nav-admin').click()
  await expect(owner.getByTestId('forum-admin')).toBeVisible()
  await owner.goto('/topic/1')
  await owner.getByRole('button', { name: 'Lock' }).click()
  await expect(owner.getByText('This topic is locked.')).toBeVisible()
  await owner.getByRole('button', { name: 'Unlock' }).click()
  await expect(owner.getByText('This topic is locked.')).toHaveCount(0)

  await guest.goto('/board/2')
  await expect(guest.getByTestId('new-topic-subject')).toHaveCount(0)
  await owner.goto('/')
  await owner.getByTestId('nav-admin').click()
  await owner.getByTestId('guest-posting').check()
  await guest.reload()
  await expect(guest.getByTestId('guest-name')).toBeVisible()
  await owner.goto('/')
  await owner.getByTestId('nav-admin').click()
  await owner.getByTestId('guest-posting').uncheck()
  await owner.getByTestId('site-name').fill('Satoshi Desk')
  await owner.getByTestId('forum-name').fill('Talk')
  await owner.getByTestId('save-names').click()
  await expect(owner.getByTestId('forum-logo')).toHaveText('Satoshi Desk')
  await expect(owner).toHaveTitle('Satoshi Desk')
  await expect(owner.getByTestId('forum-brand')).toHaveText('Talk')
  await owner.getByTestId('site-name').fill('Bitcoin')
  await owner.getByTestId('forum-name').fill('Bitcoin')
  await owner.getByTestId('save-names').click()
  await expect(owner.getByTestId('forum-logo')).toHaveText('Bitcoin')

  await ownerContext.close()
  await guestContext.close()
})
